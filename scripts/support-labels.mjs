// Generates src/lib/support/labels.ts (C43): for every Georgian label the
// support assistant's knowledge quotes, the same button's text in the
// English and Russian UI, read from messages/{ka,en,ru}.json. An answer in
// English or Russian names a button by its Georgian label (the only names
// the knowledge has); the server swaps it for the user's own UI text.
//
//   node scripts/support-labels.mjs            # rewrite the file
//   node scripts/support-labels.mjs --check    # exit 1 when it is stale
//   node scripts/support-labels.mjs --ambiguous  # list labels with several translations
//
// A Georgian string used by several keys with different translations takes
// the most common one, unless OVERRIDES names the key whose wording the
// knowledge means.

import { readFileSync, writeFileSync } from "node:fs";

const ROOT = new URL("../", import.meta.url);
const read = (path) => readFileSync(new URL(path, ROOT), "utf8");
const OUT = "src/lib/support/labels.ts";
const SOURCES = ["src/lib/support/knowledge.ts", "src/lib/support/actions.ts"];

// Georgian label -> the message key whose en/ru text the knowledge means,
// or null when the knowledge uses one label for two different buttons (the
// Georgian label is then kept rather than the wrong translation shown).
const OVERRIDES = {
  "გამოძახება": "RenterCleaners.callOut",
  "შესვლა": "AuthLogin.signIn",
  "დასრულება": "AuthRegister.finish",
  "მთავარი გვერდი": "DashboardSidebar.nav.homePage",
  "მოლოდინში": "ListingOptions.listingStatuses.pending",
  "ყველას ნახვა": "Navbar.viewAll",
};

function flatten(object, prefix = "", out = new Map()) {
  for (const [key, value] of Object.entries(object)) {
    const path = prefix ? `${prefix}.${key}` : key;
    if (value && typeof value === "object") flatten(value, path, out);
    else if (typeof value === "string") out.set(path, value.trim());
  }
  return out;
}

const ka = flatten(JSON.parse(read("messages/ka.json")));
const en = flatten(JSON.parse(read("messages/en.json")));
const ru = flatten(JSON.parse(read("messages/ru.json")));
const keysByText = new Map();
for (const [key, text] of ka) {
  if (key.startsWith("Support.canned")) continue;
  keysByText.set(text, [...(keysByText.get(text) ?? []), key]);
}

const georgian = /[Ⴀ-ჿ]/;
const quoted = /"([^"\\\n]{2,80})"/g;
const labels = new Set();
for (const file of SOURCES)
  for (const m of read(file).matchAll(quoted)) {
    const label = m[1].trim();
    if (georgian.test(label)) labels.add(label);
  }

const table = {};
const ambiguous = [];
for (const label of [...labels].sort()) {
  const keys =
    keysByText.get(label) ?? keysByText.get(label.replace(/\s*\*$/, "")) ?? [];
  const usable = keys.filter((key) => en.get(key) && ru.get(key));
  if (usable.length === 0) continue;
  const tally = new Map();
  for (const key of usable) {
    const pair = `${en.get(key)}\u0000${ru.get(key)}`;
    tally.set(pair, [...(tally.get(pair) ?? []), key]);
  }
  if (OVERRIDES[label] === null) continue;
  let chosen = OVERRIDES[label];
  if (!chosen) {
    const [best] = [...tally.values()].sort((a, b) => b.length - a.length);
    chosen = best[0];
  }
  if (tally.size > 1)
    ambiguous.push({
      label,
      chosen,
      options: [...tally.entries()].map(([pair, list]) => ({
        text: pair.replace("\u0000", " | "),
        keys: list.slice(0, 3),
      })),
    });
  table[label] = { en: en.get(chosen), ru: ru.get(chosen) };
}

// Written exactly as Prettier leaves it (keys quoted only where needed,
// trailing commas), so the format-on-save hook and --check agree.
const identifier = /^[\p{ID_Start}$_][\p{ID_Continue}$\u200c\u200d]*$/u;
const entries = Object.entries(table)
  .map(
    ([label, text]) =>
      `  ${identifier.test(label) ? label : JSON.stringify(label)}: {\n    en: ${JSON.stringify(text.en)},\n    ru: ${JSON.stringify(text.ru)},\n  },`,
  )
  .join("\n");
const body = `// Generated by scripts/support-labels.mjs from messages/{ka,en,ru}.json:
// do not edit. Re-run it after a quoted label in knowledge.ts or actions.ts,
// or its translation, changes (check-contracts C43 fails while it is stale).
//
// Georgian label -> the same button's text in the English and Russian UI.

export const UI_LABELS: Readonly<Record<string, { en: string; ru: string }>> = {
${entries}
};
`;

if (process.argv.includes("--ambiguous")) {
  for (const item of ambiguous) {
    console.log(`${item.label}  ->  ${item.chosen}`);
    for (const option of item.options)
      console.log(`    ${option.text}   [${option.keys.join(", ")}]`);
  }
} else if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = read(OUT);
  } catch {
    // missing: stale
  }
  if (current !== body) {
    console.error(`${OUT} is stale: run node scripts/support-labels.mjs`);
    process.exit(1);
  }
  console.log(`${OUT} is current (${Object.keys(table).length} labels)`);
} else {
  writeFileSync(new URL(OUT, ROOT), body);
  console.log(
    `wrote ${OUT}: ${Object.keys(table).length} of ${labels.size} labels, ${ambiguous.length} ambiguous`,
  );
}
